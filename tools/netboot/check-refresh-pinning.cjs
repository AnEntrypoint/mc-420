const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { execFileSync } = require("child_process");
const root = process.argv[2];
const script = path.join(root, "tools/netboot/refresh-apkovl.sh");
const base = fs.mkdtempSync(path.join(root, ".gm/witness-out/netboot-refresh-regression", "reg-"));
const served = path.join(base, "served");
const oldDir = path.join(base, "old");
const newDir = path.join(base, "new");
const lv2Src = path.join(base, "lv2Src");
const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); };
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");
const tarList = (archive) => execFileSync("tar", ["-tzf", archive], { encoding: "utf8" }).trim().split("\n");
const tarRead = (archive, entry) => execFileSync("tar", ["-xzOf", archive, entry]);
fs.mkdirSync(served, { recursive: true });
write(path.join(oldDir, "opt/aloop/aloop"), "OLD_BINARY");
write(path.join(oldDir, "etc/aloop.conf"), "sample_rate = 48000\n");
write(path.join(oldDir, "etc/init.d/aloop"), "OLD_INIT");
write(path.join(oldDir, "effects/home/stale.lv2/stale.ttl"), "STALE_TTL");
write(path.join(oldDir, "effects/home/stale.lv2/stale.so"), "STALE_SO");
const archive = path.join(served, "aloop.apkovl.tar.gz");
execFileSync("tar", ["--numeric-owner", "-czf", archive, "-C", oldDir, "."]);
const pin = "1111111111111111111111111111111111111111";
const binary = path.join(newDir, "aloop");
write(binary, "PINNED_BINARY");
const names = ["home-fx-lv2", "guitar-lofi-fx-lv2", "resonode-lv2", "pitchtracker-lv2", "delayverb-lv2"];
for (const n of names) {
  const b = path.join(lv2Src, n + ".lv2");
  write(path.join(b, n + ".ttl"), n + "_TTL");
  write(path.join(b, n + ".so"), n + "_SO");
}
const env = Object.assign({}, process.env, { SERVED_DIR: served, NETBOOT_PIN: pin, NETBOOT_LV2_DIR: lv2Src });
const run = execFileSync("bash", [script, binary, lv2Src], { env, encoding: "utf8", cwd: root, stdio: ["ignore", "pipe", "pipe"] });
const entries = tarList(archive);
const newBinarySha = sha(tarRead(archive, "./opt/aloop/aloop"));
const wantBinarySha = sha(fs.readFileSync(binary));
const stale = entries.filter((x) => x.includes("stale.lv2"));
const newTtl = entries.filter((x) => x.endsWith(".ttl") && !x.includes("stale.lv2"));
const newSo = entries.filter((x) => x.endsWith(".so") && !x.includes("stale.lv2"));
const ttlMatch = newTtl.every((entry) => sha(tarRead(archive, entry)) === sha(fs.readFileSync(path.join(base, "lv2Src", path.basename(path.dirname(entry)), path.basename(entry)))));
const preserved = entries.includes("./etc/aloop.conf") && entries.includes("./etc/init.d/aloop") && entries.includes("./opt/aloop/aloop");
const pass = newBinarySha === wantBinarySha && stale.length === 0 && newTtl.length === names.length && newSo.length === names.length && ttlMatch && preserved;
console.log(JSON.stringify({ pass, pin, archive, run: run.trim().split("\n").slice(0, 6), newBinarySha, wantBinarySha, staleCount: stale.length, newTtlCount: newTtl.length, newSoCount: newSo.length, ttlMatch, preserved }));
if (!pass) process.exitCode = 1;
